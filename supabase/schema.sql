-- Remove as políticas antigas (as iniciais de leitura) para recriar corretas
do $$ declare r record; begin
  for r in select schemaname, tablename, policyname from pg_policies
           where schemaname='public' and tablename in ('profiles','products','orders','order_items','product_stock','webhook_events')
  loop execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename); end loop;
end $$;

