-- Tabela de entregáveis (contas login:senha, links de guias etc.). Só o servidor acessa.
do $$
declare t_prod text;
begin
  select format_type(atttypid, atttypmod) into t_prod
    from pg_attribute where attrelid = 'public.products'::regclass and attname = 'id' and not attisdropped;
  execute format($f$
    create table if not exists public.product_stock (
      id uuid primary key default gen_random_uuid(),
      product_id %s not null references public.products(id) on delete restrict,
      secret text not null,                 -- ex.: login:senha  ou  link do guia
      note text,
      status text not null default 'available' check (status in ('available','reserved','sold')),
      order_id text,
      reserved_until timestamptz,
      sold_at timestamptz,
      created_at timestamptz not null default now()
    )$f$, t_prod);
end $$;

-- order_items com os tipos certos (detecta o tipo de orders.id e products.id)
