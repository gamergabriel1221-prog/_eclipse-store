-- ---------- 4) Perfis: criação automática SEMPRE como cliente ----------
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, name, role)
  values (new.id, new.email, coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), split_part(new.email,'@',1)), 'customer')
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- Perfis de contas que já existiam antes do trigger (todos como cliente)
insert into public.profiles (id, email, name, role)
select u.id, u.email, split_part(u.email,'@',1), 'customer' from auth.users u
where not exists (select 1 from public.profiles p where p.id = u.id);

-- Ninguém muda o próprio papel por API (só pelo SQL Editor / service_role)
create or replace function public.protect_profile_role() returns trigger
language plpgsql as $$
begin
  if new.role is distinct from old.role and auth.uid() is not null then
    raise exception 'Alterar o papel do usuário não é permitido.';
  end if;
  if new.id is distinct from old.id then raise exception 'id imutável'; end if;
  return new;
end $$;
drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role before update on public.profiles for each row execute function public.protect_profile_role();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- ---------- 5) Funções de loja (atômicas) ----------
-- Libera reservas e pedidos vencidos
create or replace function public.release_expired() returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.orders set status = 'expired' where status = 'pending' and expires_at is not null and expires_at < now();
  update public.product_stock set status = 'available', order_id = null, reserved_until = null
   where status = 'reserved' and reserved_until < now();
end $$;

-- Contagem de estoque disponível por produto
create or replace function public.stock_counts() returns table(product_id text, n bigint)
language plpgsql security definer set search_path = public as $$
begin
  perform public.release_expired();
  return query select s.product_id::text, count(*) from public.product_stock s where s.status = 'available' group by s.product_id;
end $$;

-- Cria pedido: preço SEMPRE do banco, reserva estoque com lock (nunca negativo)
create or replace function public.create_order(p_user uuid, p_email text, p_product_ids text[], p_minutes int default 30)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_order public.orders.id%type;
  v_pid public.products.id%type;
  v_price numeric(10,2); v_name text; v_total numeric(10,2) := 0;
  v_sid uuid; k text; v_open int;
begin
  if p_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_product_ids is null or array_length(p_product_ids,1) is null then raise exception 'EMPTY_CART'; end if;
  if array_length(p_product_ids,1) > 20 then raise exception 'CART_TOO_BIG'; end if;

  perform public.release_expired();
  perform pg_advisory_xact_lock(hashtext(p_user::text));  -- serializa checkouts do mesmo usuário

  select count(*) into v_open from public.orders where user_id = p_user and status = 'pending';
  if v_open >= 3 then raise exception 'TOO_MANY_PENDING'; end if;

  insert into public.orders (user_id, email, status, total, expires_at)
  values (p_user, p_email, 'pending', 0, now() + make_interval(mins => p_minutes))
  returning id into v_order;

  foreach k in array p_product_ids loop
    select p.id, p.price, p.name into v_pid, v_price, v_name
      from public.products p where p.id::text = k and p.active is true;
    if v_pid is null or v_price is null then raise exception 'INVALID_PRODUCT:%', k; end if;

    select s.id into v_sid from public.product_stock s
     where s.product_id = v_pid and s.status = 'available'
     order by s.created_at limit 1 for update skip locked;
    if v_sid is null then raise exception 'OUT_OF_STOCK:%', v_name; end if;

    update public.product_stock set status='reserved', order_id=v_order::text, reserved_until = now() + make_interval(mins => p_minutes) where id = v_sid;
    insert into public.order_items (order_id, product_id, product_name, unit_price, quantity) values (v_order, v_pid, v_name, v_price, 1);
    v_total := v_total + v_price;
    v_pid := null; v_sid := null;
  end loop;

  update public.orders set total = v_total where id = v_order;
  return jsonb_build_object('order_id', v_order::text, 'total', v_total);
end $$;

-- Cancela pedido pendente e devolve estoque (ex.: falha ao criar pagamento)
create or replace function public.cancel_order(p_order_id text) returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.orders set status='cancelled' where id::text = p_order_id and status='pending';
  update public.product_stock set status='available', order_id=null, reserved_until=null where order_id = p_order_id and status='reserved';
end $$;

-- Confirma pagamento e entrega (idempotente; chamada SÓ pelo webhook validado)
create or replace function public.fulfill_order(p_order_id text, p_payment_id text, p_paid numeric)
returns jsonb language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype; r record; v_sid uuid; v_missing int := 0;
begin
  select * into o from public.orders where id::text = p_order_id for update;
  if not found then return jsonb_build_object('result','order_not_found'); end if;
  if o.status in ('paid','paid_review') then return jsonb_build_object('result','already','status',o.status); end if;

  if p_paid < o.total then
    update public.orders set status='paid_review', mp_payment_id=p_payment_id, paid_at=now(), note='Valor pago menor que o total do pedido' where id=o.id;
    return jsonb_build_object('result','amount_mismatch');
  end if;

  -- confirma o que estava reservado
  update public.product_stock set status='sold', sold_at=now(), reserved_until=null
   where order_id = p_order_id and status='reserved';

  -- completa itens cuja reserva venceu (pega do estoque livre, com lock)
  for r in
    select oi.product_id, greatest(oi.quantity,1) - (select count(*) from public.product_stock s where s.order_id = p_order_id and s.status='sold' and s.product_id = oi.product_id) as falta
      from public.order_items oi where oi.order_id = o.id
  loop
    if r.falta > 0 then
      v_sid := null;
      select s.id into v_sid from public.product_stock s where s.product_id = r.product_id and s.status='available' order by s.created_at limit 1 for update skip locked;
      if v_sid is null then v_missing := v_missing + 1;
      else update public.product_stock set status='sold', sold_at=now(), order_id=p_order_id, reserved_until=null where id=v_sid; end if;
    end if;
  end loop;

  update public.orders set status = case when v_missing=0 then 'paid' else 'paid_review' end,
         mp_payment_id = p_payment_id, paid_at = now(), delivered_at = case when v_missing=0 then now() else null end,
         note = case when v_missing=0 then null else 'Pago, mas faltou estoque para parte dos itens' end
   where id = o.id;
  return jsonb_build_object('result', case when v_missing=0 then 'paid' else 'paid_review' end);
end $$;

-- Funções de loja: só o servidor (service_role) executa
revoke all on function public.release_expired(), public.stock_counts(), public.create_order(uuid,text,text[],int),
  public.cancel_order(text), public.fulfill_order(text,text,numeric) from public, anon, authenticated;
grant execute on function public.release_expired(), public.stock_counts(), public.create_order(uuid,text,text[],int),
  public.cancel_order(text), public.fulfill_order(text,text,numeric) to service_role;

